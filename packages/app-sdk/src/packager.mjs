import { mkdir, rename, rm, writeFile, lstat } from 'node:fs/promises';
import { resolve, join, dirname, relative, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { AppSdkError, fail, keys, plainObject } from './protocol.mjs';
import { validateManifest, validatePackagePath, manifestLimits } from './manifest.mjs';
import { readRegularFile, sha256, validatePackageDirectory } from './package-directory.mjs';
const RUNTIME = ['protocol.mjs', 'schema.mjs', 'manifest.mjs', 'worker.mjs', 'sqlite-data.mjs', 'legacy-bridge-stub.mjs'];
const runtimeDir = dirname(fileURLToPath(import.meta.url));
function inside(parent, child) { const path = relative(parent, child); return path === '' || (!path.startsWith('..') && !isAbsolute(path)); }
async function sourceFile(root, path, maximum) {
  let current = root;
  for (const part of path.split('/')) {
    current = join(current, part);
    const info = await lstat(current);
    if (info.isSymbolicLink()) fail('app_package_invalid', 'Source symlinks are forbidden');
  }
  return readRegularFile(current, maximum);
}
export async function createDirectoryPackage(options) {
  keys(options, ['sourceDirectory', 'outputDirectory', 'manifest', 'files', 'vendorSdk'], ['sourceDirectory', 'outputDirectory', 'manifest', 'files'], 'package options');
  const { manifest, files, vendorSdk = false } = options;
  const limits = manifestLimits(manifest);
  if (typeof options.sourceDirectory !== 'string' || typeof options.outputDirectory !== 'string' || typeof vendorSdk !== 'boolean') fail('app_package_invalid', 'Invalid package directory options');
  if (!plainObject(manifest) || !Array.isArray(files) || files.length > limits.files || Object.hasOwn(manifest, 'files')) fail('app_package_invalid', 'Package author manifest must omit files; supply explicit file paths');
  if (manifest.schemaVersion === 2 && vendorSdk) fail('app_package_invalid', 'Native packages do not vendor the Node worker runtime');
  const source = resolve(options.sourceDirectory);
  const output = resolve(options.outputDirectory);
  if (inside(source, output) || inside(output, source)) fail('app_package_invalid', 'Package output and source must be separate directories');
  const sourceInfo = await lstat(source);
  if (!sourceInfo.isDirectory() || sourceInfo.isSymbolicLink()) fail('app_package_invalid', 'Source must be a real directory');
  try { await lstat(output); fail('app_package_exists', 'Package output already exists'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const data = [];
  let retainedBytes = 0;
  const add = async (path, read) => {
    const bytes = await read(Math.min(limits.fileBytes, limits.packageBytes - retainedBytes));
    retainedBytes += bytes.length;
    if (retainedBytes > limits.packageBytes) fail('app_package_invalid', 'Package exceeds its byte budget');
    data.push({ path, bytes });
  };
  for (const path of files) {
    validatePackagePath(path);
    if (path.toLowerCase() === 'manifest.json') fail('app_package_invalid', 'manifest.json is generated by the packager');
    if (vendorSdk && path.toLowerCase().startsWith('sdk/')) fail('app_package_invalid', 'sdk directory is reserved for vendored runtime');
    await add(path, maximum => sourceFile(source, path, maximum));
  }
  if (vendorSdk) for (const file of RUNTIME) await add(`sdk/${file}`, maximum => readRegularFile(join(runtimeDir, file), maximum));
  const generated = validateManifest({ ...manifest, files: data.map(item => ({ path: item.path, sha256: sha256(item.bytes) })) });
  const manifestBytes = Buffer.from(`${JSON.stringify(generated, null, 2)}\n`);
  if (data.reduce((sum, item) => sum + item.bytes.length, manifestBytes.length) > limits.packageBytes) fail('app_package_invalid', 'Package exceeds its byte budget');
  await mkdir(dirname(output), { recursive: true });
  const staging = join(dirname(output), `.oviraptor-package-${randomUUID()}`);
  await mkdir(staging, { mode: 0o700 });
  let ownsOutput = false;
  try {
    for (const item of data) {
      await mkdir(dirname(join(staging, item.path)), { recursive: true });
      await writeFile(join(staging, item.path), item.bytes, { flag: 'wx', mode: manifest.schemaVersion === 2 && item.path === manifest.entry ? 0o700 : 0o600 });
    }
    await writeFile(join(staging, 'manifest.json'), manifestBytes, { flag: 'wx', mode: 0o600 });
    await validatePackageDirectory(staging);
    // Reserve the final name exclusively: POSIX directory rename can replace an empty
    // existing directory, so it is unsuitable as a portable no-overwrite publication.
    try { await mkdir(output, { mode: 0o700 }); ownsOutput = true; }
    catch (error) { if (error.code === 'EEXIST') fail('app_package_exists', 'Package output already exists'); throw error; }
    // Publish the manifest last; incomplete output cannot pass directory validation.
    const roots = [...new Set(data.map(item => item.path.split('/')[0]))];
    for (const name of roots) await rename(join(staging, name), join(output, name));
    await rename(join(staging, 'manifest.json'), join(output, 'manifest.json'));
    await rm(staging, { recursive: true, force: true });
    return await validatePackageDirectory(output);
  } catch (error) {
    await rm(staging, { recursive: true, force: true });
    if (ownsOutput) await rm(output, { recursive: true, force: true });
    if (error instanceof AppSdkError) throw error;
    fail('app_package_invalid', 'Package could not be created');
  }
}
